"""Fit the structure reliability table from the open training pool.

For each structure pattern that fires on council_train, switch its valence
push off and see which way V moves back. A firing counts as "toward" when
the push moved V toward the label's side (toward 128 for a neutral label)
and "away" otherwise. A pattern is gated (reliability 0.0) only when

  * it changed V on at least MIN_FIRINGS training sentences, and
  * P(toward-rate < 0.5) > MIN_POSTERIOR under a uniform Beta(1, 1) prior.

Everything else keeps 1.0. Only the open pool is used: the in-repo suites
are the sentences the structures were written against, so they cannot
judge them, and the holdouts are never read here.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict, Tuple

ROOT = Path(__file__).resolve().parent.parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from engine import pendulum  # noqa: E402
from engine.pendulum import compute_vadug  # noqa: E402

from . import core  # noqa: E402

MIN_FIRINGS = 20
MIN_POSTERIOR = 0.95
TABLE_PATH = ROOT / "engine" / "structure_reliability.py"


def posterior_below_half(toward: int, away: int, steps: int = 4000) -> float:
    """P(p < 0.5) for p ~ Beta(toward + 1, away + 1), by midpoint sum."""
    total = below = 0.0
    for k in range(steps):
        x = (k + 0.5) / steps
        density = x ** toward * (1.0 - x) ** away
        total += density
        if x < 0.5:
            below += density
    return below / total


def audit(rows) -> Dict[str, Tuple[int, int]]:
    """{pattern: (toward, away)} with every reliability at 1.0."""
    table = pendulum.STRUCTURE_RELIABILITY
    saved = dict(table)
    table.clear()
    try:
        scored = [compute_vadug(r["text"]) for r in rows]
        firings: Dict[str, set] = {}
        for i, (_, meta) in enumerate(scored):
            for match in meta["structures"]:
                firings.setdefault(match.pattern, set()).add(i)
        counts = {}
        for pattern, indices in sorted(firings.items()):
            toward = away = 0
            table[pattern] = 0.0
            for i in sorted(indices):
                with_push = scored[i][0].v
                without = compute_vadug(rows[i]["text"])[0].v
                if with_push == without:
                    continue
                label = rows[i]["label"]
                if label == "neutral":
                    good = abs(with_push - 128) < abs(without - 128)
                else:
                    good = (with_push - without) * (1 if label == "pos" else -1) > 0
                toward += good
                away += not good
            del table[pattern]
            counts[pattern] = (toward, away)
        return counts
    finally:
        table.clear()
        table.update(saved)


def fit(rows) -> Tuple[Dict[str, float], Dict[str, Tuple[int, int]]]:
    counts = audit(rows)
    gated = {
        pattern: 0.0 for pattern, (toward, away) in counts.items()
        if toward + away >= MIN_FIRINGS
        and posterior_below_half(toward, away) > MIN_POSTERIOR
    }
    return gated, counts


def write_table(gated: Dict[str, float], counts, n_rows: int, sha: str) -> None:
    lines = [
        "# Generated by the VADUGWI reliability fit; do not edit by hand.",
        "# Multiplier on each structure's valence push (default 1.0 when absent).",
        f"# Fitted on the open training pool only: {n_rows} sentences,",
        f"# sha256 {sha}.",
        f"# Gate rule: >= {MIN_FIRINGS} firings that changed V and",
        f"# P(toward-rate < 0.5) > {MIN_POSTERIOR} under a uniform prior.",
        "",
        "STRUCTURE_RELIABILITY = {",
    ]
    for pattern in sorted(gated):
        toward, away = counts[pattern]
        lines.append(f'    "{pattern}": {gated[pattern]},  # toward {toward}, away {away}')
    lines += ["}", ""]
    TABLE_PATH.write_text("\n".join(lines))


def main() -> int:
    rows, sha = core.load("council_train", "fit")
    gated, counts = fit(rows)
    print(f"{'pattern':30} toward  away  P(rate<0.5)  gated")
    for pattern, (toward, away) in sorted(counts.items(), key=lambda kv: -sum(kv[1])):
        p = posterior_below_half(toward, away)
        print(f"{pattern:30} {toward:6} {away:5}  {p:10.3f}  {'yes' if pattern in gated else ''}")
    write_table(gated, counts, len(rows), sha)
    print(f"wrote {TABLE_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
